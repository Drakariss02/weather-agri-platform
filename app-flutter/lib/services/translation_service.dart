  static String _currentLang = 'fr';

  static Future<void> init() async {
    final prefs = await SharedPreferences.getInstance();
    _currentLang = prefs.getString('langue') ?? 'fr';
  }

  static void setLanguage(String langCode) {
    if (_translations.containsKey(langCode)) {
      _currentLang = langCode;
    } else {
      _currentLang = 'fr';
    }
  }

  static String tr(String key) {
    return _translations[_currentLang]?[key] ??
        _translations['fr']?[key] ??
        key;
  }

  static String get currentLang => _currentLang;
